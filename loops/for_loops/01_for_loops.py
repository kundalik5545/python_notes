 
''' 
For Loops in Python

  - For Loops are used to iterate over a sequence (like a list, tuple, string) or other iterable objects. They allow you to execute a block of code     repeatedly for each item in the sequence.
'''

lists = ["apple","banana","orange","mango"]

for l in lists:
    print(f"My fav fruits is {l}!")

name = 'Abhishek'
for i in name:
    print(i, end="! ")



 